const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync(__dirname+'/index.html','utf8');
const start=html.indexOf('function orderEffectProfile('),end=html.indexOf('function simulatedActionEvent(',start);
const sortStart=html.indexOf('function sortTurnSimulationEvents('),sortEnd=html.indexOf('// v1.78.4:',sortStart);
assert(start>0&&end>start&&sortEnd>sortStart);
const ctx={$:()=>({value:'0'})};vm.createContext(ctx);
vm.runInContext(html.slice(start,end)+'\n'+html.slice(sortStart,sortEnd),ctx);
const effect=ctx.orderEffectProfile,sort=ctx.sortTurnSimulationEvents;
assert.equal(effect('こうこうのしっぽ','','move').last,true);
assert.equal(effect('まんぷくおこう','','move').last,true);
assert.equal(effect('','あとだし','move').last,true);
assert.equal(effect('こうこうのしっぽ','','switch').last,false);
assert.equal(effect('せんせいのツメ','','move').quickClaw,.2);
assert.equal(effect('','クイックドロウ','move').quickDraw,.3);
assert.equal(effect('','クイックドロウ','move').uncertain,true);
assert.equal(effect('','', 'move').uncertain,false);
const a={side:'my',idx:0,priority:0,speed:150,orderEffect:effect('こうこうのしっぽ','','move')};
const b={side:'opp',idx:1,priority:0,speed:60,orderEffect:effect('','','move')};
assert.equal(sort([a,b])[0].idx,1);
assert.equal(sort([{...a,priority:1},b])[0].idx,0);
assert.equal(ctx.orderPairUncertainty({...a,orderEffect:effect('せんせいのツメ','','move')},b),true);
assert.equal(ctx.orderPairUncertainty({...a,priority:1,orderEffect:effect('せんせいのツメ','','move')},b),false);
console.log('Order effects registry: 12 checks pass');
